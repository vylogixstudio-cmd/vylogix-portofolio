-- 1. TABEL: PORTOFOLIO
CREATE TABLE IF NOT EXISTS public.portofolio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    kategori TEXT NOT NULL CHECK (kategori IN ('web', 'design', 'video')),
    judul TEXT NOT NULL,
    deskripsi TEXT DEFAULT '',
    gambar TEXT,
    tags TEXT[] DEFAULT '{}',
    terpilih BOOLEAN DEFAULT FALSE,
    layout_class TEXT,
    link TEXT,
    id_youtube TEXT,
    rasio TEXT,
    delay TEXT DEFAULT '0ms',
    galeri JSONB DEFAULT '[]'::jsonb,
    demo_akun JSONB DEFAULT '[]'::jsonb
);

-- 2. TABEL: PRICELIST
CREATE TABLE IF NOT EXISTS public.pricelist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    kategori TEXT NOT NULL,
    nama_paket TEXT NOT NULL,
    harga BIGINT DEFAULT 0,
    fitur TEXT[] DEFAULT '{}',
    is_combo_beranda BOOLEAN DEFAULT FALSE,
    is_populer BOOLEAN DEFAULT FALSE
);

-- 3. ENABLE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.portofolio ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pricelist ENABLE ROW LEVEL SECURITY;

-- 4. KEBIJAKAN KEAMANAN (RLS POLICIES)
-- a. Semua orang (Anon & Pengunjung) bisa membaca data
DROP POLICY IF EXISTS "Public Read Portofolio" ON public.portofolio;
CREATE POLICY "Public Read Portofolio" 
ON public.portofolio FOR SELECT 
TO public 
USING (true);

DROP POLICY IF EXISTS "Public Read Pricelist" ON public.pricelist;
CREATE POLICY "Public Read Pricelist" 
ON public.pricelist FOR SELECT 
TO public 
USING (true);

-- b. Hanya Admin yang sudah login (Authenticated) yang bisa Tambah, Edit, Hapus
DROP POLICY IF EXISTS "Admin Full Access Portofolio" ON public.portofolio;
CREATE POLICY "Admin Full Access Portofolio" 
ON public.portofolio FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

DROP POLICY IF EXISTS "Admin Full Access Pricelist" ON public.pricelist;
CREATE POLICY "Admin Full Access Pricelist" 
ON public.pricelist FOR ALL 
TO authenticated 
USING (true) 
WITH CHECK (true);

